{-# LANGUAGE CPP, TemplateHaskellQuotes #-}

-- | Hedgehog generators for Template Haskell syntax, plus independent reference
-- implementations used as oracles by the properties in "Main".
module Gen
  ( genVarName
  , genConName
  , genType
  , freeVars
  , genPat
  , patVars
  , SubstCase (..)
  , genSubstCase
  , genRefinedSubstCase
  , genHeadedType
  , genKindWithArity
  , genDec
  , decNames
  , genQuotedDecs
  , allNames
  ) where

import Data.Generics (Data, everything, everywhere, mkQ, mkT)
import Data.List (nub)
import Data.Map (Map)
import qualified Data.Map as Map
import Data.Set (Set)
import qualified Data.Set as Set
import Hedgehog (Gen)
import qualified Hedgehog.Gen as Gen
import qualified Hedgehog.Range as Range
import Language.Haskell.TH
import Language.Haskell.TH.Syntax (Name (..), NameFlavour (..), mkNameU, occString)
import Language.Haskell.TH.Datatype.TyVarBndr

-- | Type variable names come from a small pool so that binders, free variables
-- and substitution targets collide often.
genVarName :: Gen Name
genVarName = Gen.element (map mkName ["a", "b", "c", "x", "y"])

genConName :: Gen Name
genConName = Gen.element (map mkName ["T", "Maybe", "Either"])

genSmallList :: Gen a -> Gen [a]
genSmallList = Gen.list (Range.linear 0 3)

genBndrSpec :: Gen TyVarBndrSpec
genBndrSpec =
  Gen.choice
    [ plainTVSpecified <$> genVarName
    , kindedTVSpecified <$> genVarName <*> Gen.small genType
    ]

#if MIN_VERSION_template_haskell(2,16,0)
genBndrUnit :: Gen TyVarBndrUnit
genBndrUnit =
  Gen.choice
    [ plainTV <$> genVarName
    , kindedTV <$> genVarName <*> Gen.small genType
    ]
#endif

-- | Generates types covering every 'Type' constructor available in the
-- template-haskell version being compiled against.
genType :: Gen Type
genType =
  Gen.recursive Gen.choice
    [ VarT <$> genVarName
    , ConT <$> genConName
    , PromotedT <$> genConName
    , TupleT <$> Gen.int (Range.linear 0 3)
    , UnboxedTupleT <$> Gen.int (Range.linear 0 3)
    , UnboxedSumT <$> Gen.int (Range.linear 2 3)
    , PromotedTupleT <$> Gen.int (Range.linear 0 3)
    , Gen.element
        [ ArrowT, EqualityT, ListT, PromotedNilT, PromotedConsT, StarT
        , ConstraintT, WildCardT, LitT (NumTyLit 1), LitT (StrTyLit "s")
#if MIN_VERSION_template_haskell(2,17,0)
        , MulArrowT
#endif
        ]
    ]
    [ Gen.subterm2 genType genType AppT
    , Gen.subterm2 genType genType SigT
    , Gen.subterm genType ParensT
    , Gen.subterm2 genType genType (\l r -> InfixT l (mkName "+") r)
    , Gen.subterm2 genType genType (\l r -> UInfixT l (mkName "+") r)
    , ForallT <$> genSmallList genBndrSpec <*> genSmallList genType <*> genType
#if MIN_VERSION_template_haskell(2,15,0)
    , Gen.subterm2 genType genType AppKindT
    , Gen.subterm genType (ImplicitParamT "p")
#endif
#if MIN_VERSION_template_haskell(2,16,0)
    , ForallVisT <$> genSmallList genBndrUnit <*> genType
#endif
#if MIN_VERSION_template_haskell(2,19,0)
    , Gen.subterm2 genType genType (\l r -> PromotedInfixT l (mkName ":+") r)
    , Gen.subterm2 genType genType (\l r -> PromotedUInfixT l (mkName ":+") r)
#endif
    ]

-- | Reference implementation: the free type variables of a type, including
-- those in kinds and contexts. Binders in a telescope scope over later binders'
-- kinds and over the body.
freeVars :: Type -> Set Name
freeVars ty = case ty of
  VarT n -> Set.singleton n
  AppT f x -> freeVars f <> freeVars x
  SigT t k -> freeVars t <> freeVars k
  ParensT t -> freeVars t
  InfixT l _ r -> freeVars l <> freeVars r
  UInfixT l _ r -> freeVars l <> freeVars r
  ForallT bndrs ctx t -> telescope bndrs (Set.unions (map freeVars (t : ctx)))
#if MIN_VERSION_template_haskell(2,15,0)
  AppKindT t k -> freeVars t <> freeVars k
  ImplicitParamT _ t -> freeVars t
#endif
#if MIN_VERSION_template_haskell(2,16,0)
  ForallVisT bndrs t -> telescope bndrs (freeVars t)
#endif
#if MIN_VERSION_template_haskell(2,19,0)
  PromotedInfixT l _ r -> freeVars l <> freeVars r
  PromotedUInfixT l _ r -> freeVars l <> freeVars r
#endif
  -- Everything else generated by 'genType' is a leaf with no type variables.
  _ -> Set.empty
  where
    telescope :: [TyVarBndr_ flag] -> Set Name -> Set Name
    telescope bndrs body =
      foldr
        (\b rest -> bndrKindVars b <> Set.delete (tvName b) rest)
        body
        bndrs

    bndrKindVars :: TyVarBndr_ flag -> Set Name
    bndrKindVars = elimTV (const Set.empty) (\_ k -> freeVars k)

-- | Generates patterns covering every 'Pat' constructor that can bind term
-- variables, in the template-haskell version being compiled against.
genPat :: Gen Pat
genPat =
  Gen.recursive Gen.choice
    [ VarP <$> genTermName
    , pure WildP
    , pure (LitP (IntegerL 1))
    ]
    [ TupP <$> genSmallList genPat
    , UnboxedTupP <$> genSmallList genPat
    , do
        arity <- Gen.int (Range.linear 2 3)
        alt <- Gen.int (Range.linear 1 arity)
        p <- genPat
        pure (UnboxedSumP p alt arity)
    , mkConP <$> genConName <*> genSmallList genPat
    , Gen.subterm2 genPat genPat (\l r -> InfixP l (mkName ":") r)
    , Gen.subterm2 genPat genPat (\l r -> UInfixP l (mkName ":") r)
    , Gen.subterm genPat ParensP
    , Gen.subterm genPat TildeP
    , Gen.subterm genPat BangP
    , AsP <$> genTermName <*> genPat
    , RecP <$> genConName <*> genSmallList ((,) <$> genFieldName <*> genPat)
    , ListP <$> genSmallList genPat
    , Gen.subterm genPat (\p -> SigP p (ConT (mkName "Int")))
    , Gen.subterm genPat (ViewP (VarE (mkName "f")))
    ]
  where
    genTermName = Gen.element (map mkName ["x", "y", "z"])
    genFieldName = Gen.element (map mkName ["f1", "f2"])
#if MIN_VERSION_template_haskell(2,18,0)
    mkConP n = ConP n []
#else
    mkConP = ConP
#endif

-- | Reference implementation: the term variables bound by a pattern, in
-- left-to-right order.
patVars :: Pat -> [Name]
patVars pat = case pat of
  VarP n -> [n]
  AsP n p -> n : patVars p
  TupP ps -> concatMap patVars ps
  UnboxedTupP ps -> concatMap patVars ps
  UnboxedSumP p _ _ -> patVars p
#if MIN_VERSION_template_haskell(2,18,0)
  ConP _ _ ps -> concatMap patVars ps
#else
  ConP _ ps -> concatMap patVars ps
#endif
  InfixP l _ r -> patVars l ++ patVars r
  UInfixP l _ r -> patVars l ++ patVars r
  ParensP p -> patVars p
  TildeP p -> patVars p
  BangP p -> patVars p
  RecP _ fps -> concatMap (patVars . snd) fps
  ListP ps -> concatMap patVars ps
  SigP p _ -> patVars p
  ViewP _ p -> patVars p
  -- Everything else generated by 'genPat' binds nothing.
  _ -> []

-- | Inputs for 'substVarsWith', plus the substitution it is expected to apply
-- to the free variables of the argument type.
data SubstCase = SubstCase
  { scTopVars :: [Name]
  , scResultType :: Type
  , scArgType :: Type
  , scExpected :: Map Name Name
  } deriving Show

-- | Generates a constructor result type @T x_1 ... x_(n-1) i@ whose parameters
-- include every free variable of the argument type, and distinct instance head
-- variables @v_1 ... v_(n-1)@ drawn from a pool that overlaps the argument
-- type's variable names, so that substituted names can clash with binders.
genSubstCase :: Gen SubstCase
genSubstCase = genSubstCaseWith (Range.singleton 0)

-- | Like 'genSubstCase', but some of the parameters @x_i@ of the result type are
-- refined to concrete types, as a GADT constructor's result type can be, e.g.
-- @C :: T Int b i@.
genRefinedSubstCase :: Gen SubstCase
genRefinedSubstCase = genSubstCaseWith (Range.linear 1 3)

-- | The range is the number of parameters of the result type that are refined
-- to concrete types rather than being variables.
genSubstCaseWith :: Range.Range Int -> Gen SubstCase
genSubstCaseWith refined = do
  argType <- genType
  extra <- genSmallList genVarName
  nRefined <- Gen.int refined
  concrete <- Gen.list (Range.singleton nRefined) (ConT <$> Gen.element (map mkName ["Int", "Bool"]))
  params <- Gen.shuffle
    (map Right (nub (Set.toList (freeVars argType) ++ extra)) ++ map Left concrete)
  pool <- Gen.shuffle (map mkName ["a", "b", "c", "x", "y", "p", "q", "r", "s", "t"])
  let topVars = take (length params) pool
      resultType =
        AppT (foldl AppT (ConT (mkName "T")) (map (either id VarT) params)) (VarT (mkName "i"))
  pure SubstCase
    { scTopVars = topVars
    , scResultType = resultType
    , scArgType = argType
    , scExpected = Map.fromList [ (x, v) | (Right x, v) <- zip params topVars ]
    }

-- | Generates a type together with the name at its head: a head type wrapped in
-- any number of applications, parentheses, kind signatures, foralls and kind
-- applications, none of which change the head.
genHeadedType :: Gen (Type, Name)
genHeadedType = do
  (ty0, name) <- genHead
  layers <- Gen.list (Range.linear 0 5) genLayer
  ty <- foldr (=<<) (pure ty0) layers
  pure (ty, name)
  where
    genHead :: Gen (Type, Name)
    genHead = Gen.choice
      [ (\n -> (ConT n, n)) <$> genConName
      , (\n -> (VarT n, n)) <$> genVarName
      , (\n -> (PromotedT n, n)) <$> genConName
      , (\k -> (TupleT k, tupleTypeName k)) <$> Gen.int (Range.linear 0 3)
      , (\k -> (UnboxedTupleT k, unboxedTupleTypeName k)) <$> Gen.int (Range.linear 0 3)
      , pure (ListT, ''[])
      , pure (ArrowT, ''(->))
      , (\l r -> (InfixT l (mkName "+") r, mkName "+")) <$> Gen.small genType <*> Gen.small genType
#if MIN_VERSION_template_haskell(2,19,0)
      , (\l r -> (PromotedInfixT l (mkName ":+") r, mkName ":+")) <$> Gen.small genType <*> Gen.small genType
#endif
      ]

    genLayer :: Gen (Type -> Gen Type)
    genLayer = Gen.element
      [ \t -> AppT t <$> Gen.small genType
      , \t -> pure (ParensT t)
      , \t -> SigT t <$> Gen.small genType
      , \t -> (\bndrs -> ForallT bndrs [] t) <$> genSmallList genBndrSpec
#if MIN_VERSION_template_haskell(2,15,0)
      , \t -> AppKindT t <$> Gen.small genType
#endif
#if MIN_VERSION_template_haskell(2,16,0)
      , \t -> (\bndrs -> ForallVisT bndrs t) <$> genSmallList genBndrUnit
#endif
      ]

-- | Generates a kind together with its arity: the number of arguments (visible
-- type arguments and arrow arguments) it takes before reaching a result kind.
-- The kind is built by wrapping a result kind in arrows, parentheses, kind
-- signatures and foralls, in any order.
genKindWithArity :: Gen (Kind, Int)
genKindWithArity = do
  result <- Gen.element [StarT, ConstraintT, ConT (mkName "Type"), VarT (mkName "k")]
  layers <- Gen.list (Range.linear 0 6) genLayer
  foldr (=<<) (pure (result, 0)) layers
  where
    genLayer :: Gen ((Kind, Int) -> Gen (Kind, Int))
    genLayer = Gen.element
      [ \(k, n) -> (\arg -> (AppT (AppT ArrowT arg) k, n + 1)) <$> Gen.small genType
      , \(k, n) -> pure (ParensT k, n)
      , \(k, n) -> (\s -> (SigT k s, n)) <$> Gen.element [StarT, ConT (mkName "Type")]
      , \(k, n) -> (\bndrs -> (ForallT bndrs [] k, n)) <$> genSmallList genBndrSpec
#if MIN_VERSION_template_haskell(2,16,0)
      , \(k, n) -> (\bndrs -> (ForallVisT bndrs k, n + length bndrs)) <$> genSmallList genBndrUnit
#endif
      ]

-- | Generates declarations of every kind that can bind names, plus some that
-- bind none. Names come from small per-namespace pools.
genDec :: Gen Dec
genDec = Gen.choice
  [ FunD <$> genValName <*> pure []
  , (\p -> ValD p (NormalB (VarE (mkName "undefined"))) []) <$> genPat
  , DataD [] <$> genTyConName <*> pure [] <*> pure Nothing <*> genSmallList genCon <*> pure []
  , NewtypeD [] <$> genTyConName <*> pure [] <*> pure Nothing <*> genCon <*> pure []
#if MIN_VERSION_template_haskell(2,20,0)
  , TypeDataD <$> genTyConName <*> pure [] <*> pure Nothing <*> genSmallList genCon
#endif
  , TySynD <$> genTyConName <*> pure [] <*> pure intT
  , ClassD [] <$> genTyConName <*> pure [] <*> pure [] <*> genSmallList genClassBodyDec
  , (\n -> ForeignD (ImportF CCall Safe "foo" n intT)) <$> genValName
  , (\n -> ForeignD (ExportF CCall "foo" n intT)) <$> genValName
  , (\n -> OpenTypeFamilyD (TypeFamilyHead n [] NoSig Nothing)) <$> genTyConName
  , (\n -> ClosedTypeFamilyD (TypeFamilyHead n [] NoSig Nothing) []) <$> genTyConName
  , (\n -> DataFamilyD n [] Nothing) <$> genTyConName
#if MIN_VERSION_template_haskell(2,15,0)
  , genDataInstD
  , InstanceD Nothing [] (ConT (mkName "C")) <$> genSmallList genDataInstD
#endif
  , (\n -> PatSynD n (PrefixPatSyn []) ImplBidir WildP) <$> genValName
  , (\n fs -> PatSynD n (RecordPatSyn fs) ImplBidir WildP) <$> genValName <*> genSmallList genFieldName
  , (\n -> SigD n intT) <$> genValName
  ]
  where
    intT = ConT (mkName "Int")
    noBang = Bang NoSourceUnpackedness NoSourceStrictness
    resT = ConT (mkName "T")

    genValName = Gen.element (map mkName ["f", "g", "h"])
    genTyConName = Gen.element (map mkName ["T", "U", "V"])
    genDataConName = Gen.element (map mkName ["A", "B", "C"])
    genFieldName = Gen.element (map mkName ["f1", "f2", "f3"])

    genCon :: Gen Con
    genCon = Gen.recursive Gen.choice
      [ NormalC <$> genDataConName <*> pure [(noBang, intT)]
      , RecC <$> genDataConName <*> genSmallList ((\f -> (f, noBang, intT)) <$> genFieldName)
      , (\n -> InfixC (noBang, intT) n (noBang, intT)) <$> genDataConName
      , GadtC <$> Gen.list (Range.linear 1 3) genDataConName <*> pure [] <*> pure resT
      , RecGadtC <$> Gen.list (Range.linear 1 3) genDataConName
          <*> genSmallList ((\f -> (f, noBang, intT)) <$> genFieldName) <*> pure resT
      ]
      [ Gen.subterm genCon (ForallC [] []) ]

    -- Declarations that can appear in a class body.
    genClassBodyDec :: Gen Dec
    genClassBodyDec = Gen.choice
      [ (\n -> SigD n intT) <$> genValName
      , FunD <$> genValName <*> pure []
      , (\n -> OpenTypeFamilyD (TypeFamilyHead n [] NoSig Nothing)) <$> genTyConName
      , (\n -> DataFamilyD n [] Nothing) <$> genTyConName
      ]

#if MIN_VERSION_template_haskell(2,15,0)
    genDataInstD :: Gen Dec
    genDataInstD = Gen.choice
      [ DataInstD [] Nothing (AppT (ConT (mkName "F")) intT) Nothing <$> genSmallList genCon <*> pure []
      , NewtypeInstD [] Nothing (AppT (ConT (mkName "F")) intT) Nothing <$> genCon <*> pure []
      ]
#endif

-- | Reference implementation: every name a declaration brings into scope, in
-- order: the declared thing itself, then its data constructors and record
-- fields, class methods and associated families, or pattern synonym fields.
-- Class default methods and instance method definitions define existing
-- names, so they bind nothing new.
decNames :: Dec -> [Name]
decNames dec = case dec of
  FunD n _ -> [n]
  ValD p _ _ -> patVars p
  DataD _ n _ _ cons _ -> n : concatMap conNames cons
  NewtypeD _ n _ _ con _ -> n : conNames con
#if MIN_VERSION_template_haskell(2,20,0)
  TypeDataD n _ _ cons -> n : concatMap conNames cons
#endif
  TySynD n _ _ -> [n]
  ClassD _ n _ _ body -> n : concatMap classBodyNames body
  ForeignD (ImportF _ _ _ n _) -> [n]
  ForeignD (ExportF {}) -> []
  OpenTypeFamilyD (TypeFamilyHead n _ _ _) -> [n]
  ClosedTypeFamilyD (TypeFamilyHead n _ _ _) _ -> [n]
  DataFamilyD n _ _ -> [n]
  DataInstD _ _ _ _ cons _ -> concatMap conNames cons
  NewtypeInstD _ _ _ _ con _ -> conNames con
  InstanceD _ _ _ body -> concatMap decNames [ d | d <- body, isDataInst d ]
  PatSynD n (RecordPatSyn fs) _ _ -> n : fs
  PatSynD n _ _ _ -> [n]
  _ -> []
  where
    conNames con = case con of
      NormalC n _ -> [n]
      RecC n fs -> n : [ f | (f, _, _) <- fs ]
      InfixC _ n _ -> [n]
      ForallC _ _ c -> conNames c
      GadtC ns _ _ -> ns
      RecGadtC ns fs _ -> ns ++ [ f | (f, _, _) <- fs ]

    classBodyNames d = case d of
      SigD n _ -> [n]
      OpenTypeFamilyD {} -> decNames d
      DataFamilyD {} -> decNames d
      _ -> []

    isDataInst d = case d of
      DataInstD {} -> True
      NewtypeInstD {} -> True
      _ -> False

-- | Generates declarations as a declaration quote would produce them: every
-- name, bound or not, is made fresh ('NameU'), with the same unique for every
-- occurrence of the same name.
genQuotedDecs :: Gen [Dec]
genQuotedDecs = do
  decs <- Gen.list (Range.linear 1 4) genDec
  let bases = nub [ occString occ | Name occ NameS <- allNames decs ]
      uniques = Map.fromList (zip bases [1 ..])
      freshen n@(Name occ NameS) =
        maybe n (mkNameU (occString occ) . fromInteger) (Map.lookup (occString occ) uniques)
      freshen n = n
  pure (everywhere (mkT freshen) decs)

-- | Every 'Name' occurring in a value, in traversal order.
allNames :: Data a => a -> [Name]
allNames = everything (++) (mkQ [] (\n -> [n]))
